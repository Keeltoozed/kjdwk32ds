import numpy as np
import random

def simulate(label, buckets, start=20.0, trades_per_day=32, days=30):
    capital = start
    peak = start
    max_dd = 0
    wins = 0
    total = 0
    
    for i in range(trades_per_day * days):
        if capital < 4.0:
            break
        trade_size = max(4.0, min(100.0, capital * 0.10))
        
        roll = random.random()
        cumulative = 0
        pnl_pct = 0
        for prob, avg_pnl in buckets:
            cumulative += prob
            if roll <= cumulative:
                pnl_pct = avg_pnl * np.random.uniform(0.7, 1.3)
                break
        
        if pnl_pct > 0: wins += 1
        total += 1
        
        capital += trade_size * (pnl_pct / 100.0) - 0.075
        if capital > peak: peak = capital
        dd = (peak - capital) / peak
        if dd > max_dd: max_dd = dd
    
    ev = sum(p * a for p, a in buckets)
    wr = wins / total if total > 0 else 0
    print(f"\n{'='*60}")
    print(f"  {label}")
    print(f"{'='*60}")
    print(f"  Матожидание 1 сделки: {ev:+.2f}%")
    print(f"  Сделок выполнено:     {total}")
    print(f"  Win Rate:             {wr*100:.1f}%")
    print(f"  Старт:                ${start:.2f}")
    print(f"  Итого:                ${capital:,.2f}")
    if capital >= start:
        print(f"  🟢 Прибыль:           ${capital - start:,.2f} (+{(capital-start)/start*100:,.1f}%)")
    else:
        print(f"  🔴 Убыток:            ${start - capital:,.2f} ({(capital-start)/start*100:,.1f}%)")
    print(f"  Max Drawdown:         {max_dd*100:.1f}%")

random.seed(42)

